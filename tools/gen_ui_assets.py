"""Embed the vendored nk_ui assets in ``src/ui/nk_ui_assets.c`` and Pataport's
easter-egg clip in ``src/ui/egg_assets.c``.

The native player draws the launcher's button prompts from Kenney's CC0 "Input
Prompts" glyphs and can play three CC0 "Interface Sounds" clips. Both packs are
vendored, file by file, under ``third_party/kenney/`` (see its ``PROVENANCE.md``).
The game runtime carries its own separate embedding: the easter-egg clip,
Pataport's own audio committed under ``assets/easter_egg/`` (see its
``PROVENANCE.md``), played by ``src/rt/easter_egg.c``. Embedding the bytes in
the binaries means neither the player nor the runtime needs extra staged files
or run-time path lookups, and the SDL-free tests decode exactly the bytes the
binaries ship.

Every ``*.png`` under ``third_party/kenney/input-prompts/``, every ``*.wav``
under ``third_party/kenney/interface-sounds/`` and every ``*.ogg`` under
``assets/easter_egg/`` is embedded, sorted by name, as ``"<pack>/<file>"``. The
output is deterministic: the same inputs give the same bytes on every host.

    python tools/gen_ui_assets.py                  # rewrite both embedding files
    python tools/gen_ui_assets.py --out <file>     # write the launcher's elsewhere
    python tools/gen_ui_assets.py --check          # exit 1 when a committed file is stale

``python tools/regen_all.py`` runs this step with the other generators.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("src/ui/nk_ui_assets.c")
EGG_OUTPUT = Path("src/ui/egg_assets.c")
KENNEY_DIR = Path("third_party/kenney")
PACKS: tuple[tuple[str, str], ...] = (
    ("input-prompts", "*.png"),
    ("interface-sounds", "*.wav"),
)
# Refuse anything that is plainly not a small UI asset.
MAX_ASSET_BYTES = 64 * 1024
# The easter-egg pack lives outside third_party/kenney (the clip is Pataport's
# own, not vendored third-party work) and carries its own, larger cap: one
# Vorbis clip of a few seconds.
EGG_DIR = Path("assets/easter_egg")
EGG_PACK = ("easter-egg", "*.ogg")
EGG_MAX_ASSET_BYTES = 256 * 1024
BYTES_PER_LINE = 16

KENNEY_NOTE = [
    "/* Generated by tools/gen_ui_assets.py from third_party/kenney/ (CC0-1.0 assets by Kenney,",
    "   www.kenney.nl; see third_party/kenney/PROVENANCE.md). */",
]
EGG_NOTE = [
    "/* Generated by tools/gen_ui_assets.py from assets/easter_egg/ (Pataport's own",
    "   easter-egg clip; see assets/easter_egg/PROVENANCE.md). */",
]


def _pack_assets(directory: Path, pack: str, pattern: str, cap: int) -> list[tuple[str, bytes]]:
    files = sorted(directory.glob(pattern), key=lambda path: path.name)
    if not files:
        raise SystemExit(f"gen_ui_assets: no {pattern} under {directory}")
    assets: list[tuple[str, bytes]] = []
    for path in files:
        data = path.read_bytes()
        if not data or len(data) > cap:
            raise SystemExit(f"gen_ui_assets: {path.name} is {len(data)} bytes")
        assets.append((f"{pack}/{path.name}", data))
    return assets


def collect(root: Path = ROOT) -> list[tuple[str, bytes]]:
    assets: list[tuple[str, bytes]] = []
    for pack, pattern in PACKS:
        assets += _pack_assets(root / KENNEY_DIR / pack, pack, pattern, MAX_ASSET_BYTES)
    return assets


def collect_egg(root: Path = ROOT) -> list[tuple[str, bytes]]:
    pack, pattern = EGG_PACK
    return _pack_assets(root / EGG_DIR, pack, pattern, EGG_MAX_ASSET_BYTES)


def _symbol(name: str, prefix: str) -> str:
    return prefix + "".join(ch if ch.isalnum() else "_" for ch in name)


def render(assets: list[tuple[str, bytes]], *, header: str, note: list[str],
           symbol_prefix: str, table: str) -> str:
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/* Copyright (C) 2026 the Nakagawa Recomp authors */",
        "/* AUTOGENERATED FILE - DO NOT EDIT DIRECTLY */",
        *note,
        "",
        f'#include "{header}"',
        "",
        "#include <string.h>",
        "",
    ]
    total = 0
    for name, data in assets:
        total += len(data)
        lines.append(f"/* {name}, {len(data)} bytes */")
        lines.append(f"static const unsigned char {_symbol(name, symbol_prefix)}[{len(data)}] = {{")
        for start in range(0, len(data), BYTES_PER_LINE):
            chunk = data[start:start + BYTES_PER_LINE]
            lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append(f"/* {len(assets)} assets, {total} bytes. */")
    lines.append(f"const NkUiEmbeddedAsset {table}_embedded_assets[] = {{")
    for name, data in assets:
        lines.append(f'    {{"{name}", {_symbol(name, symbol_prefix)}, {len(data)}u}},')
    lines.append("};")
    lines.append("")
    lines.append(
        f"const size_t {table}_embedded_asset_count = "
        f"sizeof({table}_embedded_assets) / sizeof({table}_embedded_assets[0]);"
    )
    lines.append("")
    lines.append(f"const NkUiEmbeddedAsset *{table}_embedded_asset(const char *name) {{")
    lines.append("    size_t i;")
    lines.append("    if (name == NULL) {")
    lines.append("        return NULL;")
    lines.append("    }")
    lines.append(f"    for (i = 0; i < {table}_embedded_asset_count; ++i) {{")
    lines.append(f"        if (strcmp({table}_embedded_assets[i].name, name) == 0) {{")
    lines.append(f"            return &{table}_embedded_assets[i];")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _display(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / OUTPUT, help="output file")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when a committed file differs from a fresh generation")
    args = parser.parse_args(argv)
    # The runtime embedding lands beside the launcher's, so a --out run (regen_all
    # renders into a temporary directory) never writes outside the caller's target.
    egg_out = args.out.parent / EGG_OUTPUT.name
    outputs = (
        (args.out, render(collect(), header="nk_ui_assets.h", note=KENNEY_NOTE,
                          symbol_prefix="k_", table="nk_ui")),
        (egg_out, render(collect_egg(), header="egg_assets.h", note=EGG_NOTE,
                         symbol_prefix="egg_", table="egg")),
    )
    if args.check:
        for path, text in outputs:
            current = path.read_bytes() if path.is_file() else b""
            if current != text.encode("utf-8"):
                print(f"gen_ui_assets: {_display(path)} is stale; run python tools/regen_all.py",
                      file=sys.stderr)
                return 1
        print(f"gen_ui_assets: {_display(args.out)} and {_display(ROOT / EGG_OUTPUT)} are current")
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
